"""Writes the Android vector drawables (launcher foreground, banner, notification and in-app logo) from the
logo masters, so the app always carries exactly the master geometry."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MASTERS = ROOT / "branding" / "masters"
RES = ROOT / "app" / "src" / "main" / "res" / "drawable"


def paths(svg):
    """(d, transform) for every <path> in a master."""
    out = []
    for m in re.finditer(r'<path([^>]*)/>', (MASTERS / svg).read_text()):
        attrs = m.group(1)
        d = re.search(r'\sd="([^"]+)"', attrs).group(1)
        t = re.search(r'transform="([^"]+)"', attrs)
        out.append((d, t.group(1) if t else None))
    return out


def group(transform, inner):
    """An SVG translate/scale transform as a <group>."""
    if not transform:
        return inner
    tx = ty = 0.0
    s = 1.0
    if (m := re.search(r"translate\(([-\d.]+) ([-\d.]+)\)", transform)):
        tx, ty = float(m.group(1)), float(m.group(2))
    if (m := re.search(r"scale\(([-\d.]+)\)", transform)):
        s = float(m.group(1))
    return (f'<group android:translateX="{tx:g}" android:translateY="{ty:g}" android:scaleX="{s:g}" '
            f'android:scaleY="{s:g}">{inner}</group>')


def vector(name, width_dp, height_dp, vw, vh, body, comment):
    xml = (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} Generated by branding/tools/android_assets.py. -->\n'
           f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
           f'    android:width="{width_dp}dp" android:height="{height_dp}dp"\n'
           f'    android:viewportWidth="{vw:g}" android:viewportHeight="{vh:g}">\n    {body}\n</vector>\n')
    (RES / name).write_text(xml)


def seal_path(color, d):
    return f'<path android:fillColor="{color}" android:fillType="evenOdd" android:pathData="{d}"/>'


SALMON, CHARCOAL, WHITE = "#FFB4A9", "#131314", "#FFFFFF"
small = paths("tubeguard-symbol-small.svg")[0][0]
regular = paths("tubeguard-symbol.svg")[0][0]

# Launcher foreground: the small-size cut, 60 of the 108 dp (inside the 66 dp safe zone), centred.
k = 60 / 232
off = 54 - 128 * k
vector("ic_launcher_foreground.xml", 108, 108, 108, 108,
       group(f"translate({off} {off}) scale({k})", seal_path(SALMON, small)), "Launcher foreground: the seal.")
vector("ic_launcher_monochrome.xml", 108, 108, 108, 108,
       group(f"translate({off} {off}) scale({k})", seal_path(WHITE, small)), "Themed-icon (monochrome) layer.")

# Notification and status bar: white seal on a 24 dp canvas.
vector("ic_notification.xml", 24, 24, 256, 256, seal_path(WHITE, small), "Notification icon.")

# In-app logo (top bar): the regular seal in the brand colour.
vector("ic_logo.xml", 48, 48, 256, 256, seal_path(SALMON, regular), "The logo, for the app's top bar.")

# TV launcher banner, 320 x 180 dp: charcoal with the horizontal lockup in salmon, 220 dp wide, centred.
lockup = (MASTERS / "tubeguard-horizontal.svg").read_text()
lw, lh = [float(v) for v in re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', lockup).groups()]
scale = 220 / lw
bx, by = (320 - lw * scale) / 2, (180 - lh * scale) / 2
inner = ""
for d, t in paths("tubeguard-horizontal.svg"):
    inner += group(t, f'<path android:fillColor="{SALMON}" android:fillType="evenOdd" android:pathData="{d}"/>')
body = (f'<path android:fillColor="{CHARCOAL}" android:pathData="M0 0 H320 V180 H0 Z"/>'
        + group(f"translate({bx} {by}) scale({scale})", inner))
vector("banner.xml", 320, 180, 320, 180, body, "Android TV launcher banner.")
print("android vectors written to", RES)
